// Package secretfp computes the keyed fingerprint a plane reports for each shared secret it holds
// (FEI-40). Services share secrets in pairs; a wrong value on one side used to surface only as
// refusals later. Each plane reports, in its posture report, a fingerprint per relationship it takes
// part in, and the deploy-time verifier (feir-os deploy/posture/verify-posture.sh) compares the pairs.
//
// fingerprint(secret, relationship) = lowercase hex of the first 16 bytes of
// HMAC-SHA256(key = secret, message = "feir-secret-alignment/v1:" + relationship).
//
// It is not the secret and does not reveal it, but it is only as private as the secret is strong:
// a fingerprint lets someone who holds it test guesses for a low-entropy secret offline. The report
// that carries it is served only behind the plane's operator credential. The golden vectors
// (vectors/secret-fingerprint.v1.json, owned by feir-os, generated by an independent Python
// reference) pin the construction across every plane.
package secretfp

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
)

// labelPrefix is part of the message so a fingerprint made here cannot be confused with an HMAC the
// plane computes for any other purpose.
const labelPrefix = "feir-secret-alignment/v1:"

// Fingerprint returns the fingerprint of secret for the relationship, or "" for an empty secret
// (an unset secret has no fingerprint: the caller omits the relationship).
func Fingerprint(secret, relationship string) string {
	if secret == "" {
		return ""
	}
	mac := hmac.New(sha256.New, []byte(secret))
	mac.Write([]byte(labelPrefix + relationship))
	return hex.EncodeToString(mac.Sum(nil)[:16])
}

// Fingerprints fingerprints each non-empty secret of a rotation list, in order, without duplicates.
// It returns nil when there is nothing to fingerprint.
func Fingerprints(secrets []string, relationship string) []string {
	var out []string
	seen := map[string]struct{}{}
	for _, s := range secrets {
		f := Fingerprint(s, relationship)
		if f == "" {
			continue
		}
		if _, dup := seen[f]; dup {
			continue
		}
		seen[f] = struct{}{}
		out = append(out, f)
	}
	return out
}
